//! A project's review knowledge base: what Forge learned about it, rendered
//! as four files. `architecture.md` and `patterns.json` are stored;
//! `learned-rules.md` and `false-positives.json` are derived from feedback
//! whenever they are read. Pure; the daemon stores and redacts.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use domain::{ReviewSuppression, Severity, SuppressionKind};

pub const ARCHITECTURE: &str = "architecture.md";
pub const PATTERNS: &str = "patterns.json";
pub const LEARNED_RULES: &str = "learned-rules.md";
pub const FALSE_POSITIVES: &str = "false-positives.json";
/// The two files a person or the daemon may write.
pub const STORED: [&str; 2] = [ARCHITECTURE, PATTERNS];
pub const MAX_FILE_BYTES: usize = 256 * 1024;
pub const MAX_PROJECT_BYTES: usize = 1024 * 1024;
pub const MAX_AGE_DAYS: i64 = 90;
const MODULE_DEPTH: usize = 2;

/// The `## <module>` heading's anchor, as a finding's `kb_ref` cites it.
#[must_use]
pub fn slug(module: &str) -> String {
    module
        .chars()
        .map(|c| {
            if c.is_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect::<String>()
        .trim_matches('-')
        .to_owned()
}

/// A path's module: its directories to depth two, `(root)` for a top-level file.
#[must_use]
pub fn module(path: &str) -> String {
    let dirs: Vec<&str> = path.split('/').collect();
    if dirs.len() <= 1 {
        return "(root)".to_owned();
    }
    dirs[..(dirs.len() - 1).min(MODULE_DEPTH)].join("/")
}

/// `architecture.md` from the graph's files `(path, language)` and file
/// imports `(from, to)`.
#[must_use]
pub fn architecture(
    files: &[(String, String)],
    imports: &[(String, String)],
    git_oid: &str,
) -> String {
    let mut modules: BTreeMap<String, (usize, BTreeSet<String>)> = BTreeMap::new();
    for (path, lang) in files {
        let entry = modules.entry(module(path)).or_default();
        entry.0 += 1;
        if !lang.is_empty() {
            entry.1.insert(lang.clone());
        }
    }
    let mut links: BTreeMap<(String, String), usize> = BTreeMap::new();
    for (from, to) in imports {
        let (from, to) = (module(from), module(to));
        if from != to {
            *links.entry((from, to)).or_default() += 1;
        }
    }
    let mut out = format!(
        "# Architecture\n\nGenerated by Forge from the codebase graph at `{git_oid}`: {} module(s), {} file(s).\n",
        modules.len(),
        files.len()
    );
    for (name, (count, langs)) in &modules {
        let _ = write!(out, "\n## {name}\n\n- {count} file(s)");
        if !langs.is_empty() {
            let _ = write!(
                out,
                " in {}",
                langs.iter().cloned().collect::<Vec<_>>().join(", ")
            );
        }
        out.push('\n');
        let imported: Vec<String> = links
            .iter()
            .filter(|((from, _), _)| from == name)
            .map(|((_, to), n)| format!("{to} ({n})"))
            .collect();
        if !imported.is_empty() {
            let _ = writeln!(out, "- imports {}", imported.join(", "));
        }
    }
    clip(&out, MAX_FILE_BYTES).to_owned()
}

/// `learned-rules.md` from the project's active suppressions.
#[must_use]
pub fn learned_rules(suppressions: &[ReviewSuppression]) -> String {
    let mut out = String::from(
        "# Learned rules\n\nWhat this project's feedback has taught the reviewer to leave out.\n",
    );
    if suppressions.is_empty() {
        out.push_str("\nNone yet.\n");
    }
    for suppression in suppressions {
        let what = match suppression.kind {
            SuppressionKind::Rule => format!("rule `{}`", suppression.value),
            SuppressionKind::Category => format!("category `{}`", suppression.value),
            _ => format!(
                "finding `{}`{}",
                suppression.value,
                suppression
                    .severity
                    .map(|s| format!(" at {s:?}"))
                    .unwrap_or_default()
            ),
        };
        let _ = writeln!(out, "- {what}: {}", suppression.reason);
    }
    clip(&out, MAX_FILE_BYTES).to_owned()
}

/// One 👎 the project's feedback holds.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FalsePositive {
    pub fingerprint: String,
    /// `None` once the run it came from was pruned.
    pub path: Option<String>,
    pub rule_id: Option<String>,
    pub severity: Severity,
}

/// `false-positives.json`, newest first as given, within the file cap.
#[must_use]
pub fn false_positives(rows: &[FalsePositive]) -> String {
    let mut items = Vec::new();
    let mut size = 2;
    for row in rows {
        let item = serde_json::json!({
            "fingerprint": row.fingerprint,
            "path": row.path,
            "rule_id": row.rule_id,
            "severity": format!("{:?}", row.severity),
        });
        size += item.to_string().len() + 1;
        if size > MAX_FILE_BYTES {
            break;
        }
        items.push(item);
    }
    serde_json::to_string_pretty(&items).unwrap_or_else(|_| "[]".to_owned())
}

/// `patterns.json` from one pattern per entry.
#[must_use]
pub fn patterns_json(patterns: &[String]) -> String {
    serde_json::to_string_pretty(patterns).unwrap_or_else(|_| "[]".to_owned())
}

/// The `learned` patterns to store beside the live `stored` ones, in order and
/// deduplicated. One that would take `patterns.json` or the project, with
/// `others` bytes in its other files, over its cap is refused, as a person's
/// write would be; nothing stored is dropped for it.
#[must_use]
pub fn admit_patterns(stored: &[String], others: usize, learned: &[String]) -> Vec<String> {
    let rendered = |item: &String| serde_json::to_string(item).map_or(usize::MAX, |s| s.len());
    // `patterns_json`'s pretty list: `[\n` and `\n]`, then two spaces and `,\n` per item.
    let mut size = 2 + stored
        .iter()
        .map(|item| rendered(item).saturating_add(4))
        .fold(0usize, usize::saturating_add);
    let mut seen: BTreeSet<&str> = stored.iter().map(String::as_str).collect();
    let mut admitted = Vec::new();
    for item in learned {
        if !seen.insert(item) {
            continue;
        }
        let grown = size.saturating_add(rendered(item).saturating_add(4));
        if grown > MAX_FILE_BYTES || others.saturating_add(grown) > MAX_PROJECT_BYTES {
            continue;
        }
        size = grown;
        admitted.push(item.clone());
    }
    admitted
}

/// `patterns.json` as a person wrote it: a JSON list of strings.
///
/// # Errors
/// Anything else.
pub fn parse_patterns(text: &str) -> Result<Vec<String>, String> {
    let value: serde_json::Value = serde_json::from_str(text)
        .map_err(|error| format!("patterns.json is not JSON: {error}"))?;
    let items = value
        .as_array()
        .ok_or_else(|| "patterns.json must be a list of strings".to_owned())?;
    items
        .iter()
        .map(|item| {
            item.as_str()
                .map(|text| text.trim().to_owned())
                .ok_or_else(|| "patterns.json must be a list of strings".to_owned())
        })
        .filter(|item| item.as_ref().map_or(true, |text| !text.is_empty()))
        .collect()
}

/// The `architecture.md` sections of the modules `paths` are in, then the
/// learned rules, each a `(kb_ref, text)`, within `budget` bytes.
#[must_use]
pub fn excerpts(
    architecture: &str,
    learned: &str,
    paths: &[String],
    budget: usize,
) -> Vec<(String, String)> {
    let wanted: BTreeSet<String> = paths.iter().map(|path| module(path)).collect();
    let mut out = Vec::new();
    let mut used = 0usize;
    let mut push = |reference: String, text: String, out: &mut Vec<(String, String)>| {
        if used + reference.len() + text.len() > budget {
            return false;
        }
        used += reference.len() + text.len();
        out.push((reference, text));
        true
    };
    for section in architecture.split("\n## ").skip(1) {
        let (name, body) = section.split_once('\n').unwrap_or((section, ""));
        if wanted.contains(name.trim()) {
            let reference = format!("{ARCHITECTURE}#{}", slug(name.trim()));
            if !push(reference, body.trim().to_owned(), &mut out) {
                return out;
            }
        }
    }
    if learned.contains("\n- ") {
        push(
            LEARNED_RULES.to_owned(),
            learned.trim().to_owned(),
            &mut out,
        );
    }
    out
}

/// All four files as one Markdown document.
#[must_use]
pub fn export(files: &[domain::KbFile]) -> String {
    let mut out = String::from("# Forge Review knowledge base\n");
    for file in files {
        let fence = if file.file.ends_with(".json") {
            "```json\n"
        } else {
            ""
        };
        let close = if fence.is_empty() { "" } else { "\n```" };
        let _ = write!(
            out,
            "\n---\n\n<!-- {} ({}) -->\n\n{fence}{}{close}\n",
            file.file,
            file.source,
            file.content.trim_end()
        );
    }
    out
}

/// Whether `content` for `file` may be stored, given what the project holds
/// in its other stored files.
///
/// # Errors
/// A file that is not stored, or over its cap or the project's.
pub fn check_write(file: &str, content: &str, others: usize) -> Result<(), String> {
    if !STORED.contains(&file) {
        return Err(format!(
            "{file} is derived from feedback and cannot be written; only {} can",
            STORED.join(" and ")
        ));
    }
    if content.len() > MAX_FILE_BYTES {
        return Err(format!("{file} is over {} KiB", MAX_FILE_BYTES / 1024));
    }
    if others + content.len() > MAX_PROJECT_BYTES {
        return Err(format!(
            "the knowledge base would be over {} KiB",
            MAX_PROJECT_BYTES / 1024
        ));
    }
    Ok(())
}

fn clip(text: &str, max: usize) -> &str {
    if text.len() <= max {
        return text;
    }
    let mut end = max;
    while !text.is_char_boundary(end) {
        end -= 1;
    }
    &text[..end]
}

