use super::*;

fn files() -> Vec<(String, String)> {
    [
        ("crates/daemon/src/core.rs", "rust"),
        ("crates/daemon/src/review.rs", "rust"),
        ("crates/review/src/lib.rs", "rust"),
        ("web/app.ts", "typescript"),
        ("README.md", ""),
    ]
    .iter()
    .map(|(p, l)| ((*p).to_owned(), (*l).to_owned()))
    .collect()
}

#[test]
fn modules_are_directories_to_depth_two() {
    assert_eq!(module("crates/daemon/src/core.rs"), "crates/daemon");
    assert_eq!(module("web/app.ts"), "web");
    assert_eq!(module("README.md"), "(root)");
    assert_eq!(slug("crates/daemon"), "crates-daemon");
}

#[test]
fn architecture_counts_files_languages_and_module_imports() {
    let imports = vec![
        (
            "crates/daemon/src/review.rs".to_owned(),
            "crates/review/src/lib.rs".to_owned(),
        ),
        (
            "crates/daemon/src/core.rs".to_owned(),
            "crates/review/src/lib.rs".to_owned(),
        ),
        (
            "crates/daemon/src/core.rs".to_owned(),
            "crates/daemon/src/review.rs".to_owned(),
        ),
    ];
    let text = architecture(&files(), &imports, "abc");
    assert!(text.starts_with("# Architecture\n\nGenerated by Forge from the codebase graph at `abc`: 4 module(s), 5 file(s).\n"));
    assert!(
        text.contains("\n## crates/daemon\n\n- 2 file(s) in rust\n- imports crates/review (2)\n"),
        "{text}"
    );
    assert!(text.contains("\n## web\n\n- 1 file(s) in typescript\n"));
    assert!(text.contains("\n## (root)\n\n- 1 file(s)\n"));
}

#[test]
fn learned_rules_and_false_positives_render_from_feedback() {
    let rules = learned_rules(&[ReviewSuppression {
        kind: SuppressionKind::Rule,
        value: "no-unwrap".into(),
        severity: None,
        reason: "dismissed 3 times".into(),
    }]);
    assert!(rules.contains("- rule `no-unwrap`: dismissed 3 times"));
    assert!(learned_rules(&[]).contains("None yet."));
    let json = false_positives(&[FalsePositive {
        fingerprint: "f1".into(),
        path: Some("src/a.rs".into()),
        rule_id: None,
        severity: Severity::P2,
    }]);
    let parsed: serde_json::Value = serde_json::from_str(&json).expect("json");
    assert_eq!(parsed[0]["fingerprint"], "f1");
    assert_eq!(parsed[0]["severity"], "P2");
    assert_eq!(parsed[0]["path"], "src/a.rs");
}

#[test]
fn patterns_round_trip_and_bad_ones_are_refused() {
    let json = patterns_json(&["errors are typed".into()]);
    assert_eq!(
        parse_patterns(&json),
        Ok(vec!["errors are typed".to_owned()])
    );
    assert!(parse_patterns("{}").is_err());
    assert!(parse_patterns("[1]").is_err());
    assert_eq!(parse_patterns("[\"\", \" x \"]"), Ok(vec!["x".to_owned()]));
}

#[test]
fn excerpts_pick_the_diffs_modules_within_the_budget() {
    let text = architecture(&files(), &[], "abc");
    let learned = learned_rules(&[ReviewSuppression {
        kind: SuppressionKind::Category,
        value: "style".into(),
        severity: None,
        reason: "dismissed 5 times".into(),
    }]);
    let picked = excerpts(
        &text,
        &learned,
        &["crates/daemon/src/graph.rs".into()],
        32 * 1024,
    );
    assert_eq!(picked[0].0, "architecture.md#crates-daemon");
    assert!(picked[0].1.contains("2 file(s)"));
    assert_eq!(picked[1].0, "learned-rules.md");
    assert_eq!(picked.len(), 2);
    let tight = excerpts(&text, &learned, &["crates/daemon/src/graph.rs".into()], 60);
    assert_eq!(tight.len(), 1, "{tight:?}");
    assert!(excerpts(&text, &learned, &["web/x.ts".into()], 10).is_empty());
}

#[test]
fn writes_are_limited_to_stored_files_and_the_caps() {
    assert!(check_write(ARCHITECTURE, "x", 0).is_ok());
    assert!(check_write(LEARNED_RULES, "x", 0)
        .unwrap_err()
        .contains("derived"));
    assert!(check_write(PATTERNS, &"x".repeat(MAX_FILE_BYTES + 1), 0).is_err());
    assert!(check_write(PATTERNS, "x", MAX_PROJECT_BYTES).is_err());
    let big = "y".repeat(MAX_FILE_BYTES * 2);
    assert!(
        architecture(&[(format!("{big}/a.rs"), String::new())], &[], "o").len() <= MAX_FILE_BYTES
    );
}

#[test]
fn the_export_carries_every_file() {
    let file = |name: &str, content: &str| domain::KbFile {
        file: name.into(),
        content: content.into(),
        source: "daemon".into(),
        updated_at: None,
    };
    let text = export(&[file(ARCHITECTURE, "# Architecture"), file(PATTERNS, "[]")]);
    assert!(text.starts_with("# Forge Review knowledge base\n"));
    assert!(text.contains("<!-- architecture.md (daemon) -->\n\n# Architecture\n"));
    assert!(text.contains("<!-- patterns.json (daemon) -->\n\n```json\n[]\n```"));
}
