// CSS provides the first-paint theme before the runtime applies derived values.
import { resolve } from "node:path";
import { palettes, staticTokens, toCssVariables, type ThemeBaseId } from "../src/theme/tokens";
import { syntaxRules, syntaxVariables } from "../src/theme/editorTheme";

const out = resolve(import.meta.dir, "../src/theme/tokens.css");

function block(selector: string, vars: Record<string, string>): string {
  const body = Object.entries(vars)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  return `${selector} {\n${body}\n}\n`;
}

function themeVariables(id: ThemeBaseId): Record<string, string> {
  return { ...toCssVariables(palettes[id]), ...syntaxVariables(id) };
}

const order = Object.keys(palettes) as ThemeBaseId[];
const parts = [
  "/* Generated by scripts/generate-tokens.ts — do not edit by hand. */",
  block(':root, [data-theme="forge-dark"]', themeVariables("forge-dark")),
  ...order
    .filter((id) => id !== "forge-dark")
    .map((id) => block(`[data-theme="${id}"]`, themeVariables(id))),
  "/* Semantic layer and scale — theme-independent, so emitted once. */",
  block(":root", staticTokens()),
  "/* Syntax colour by scope, for every DOM surface that paints highlighted code. */",
  syntaxRules(),
];

await Bun.write(out, `${parts.join("\n")}\n`);
console.log(`wrote ${out}`);
